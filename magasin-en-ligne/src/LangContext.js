const LangContext = createContext();

export const LangProvider = ({ children }) => {
  const [langue, setLangue] = useState(() => localStorage.getItem('langue') || 'fr');

  useEffect(() => {
    localStorage.setItem('langue', langue);
    document.documentElement.lang = langue;
  }, [langue]);

  const t = (cle) => TRADUCTIONS[langue]?.[cle] ?? TRADUCTIONS.fr[cle] ?? cle;

  return (
    <LangContext.Provider value={{ langue, setLangue, t }}>
      {children}
    </LangContext.Provider>
  );
};

export const useLang = () => {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error('useLang doit être utilisé dans un LangProvider');
  return ctx;
};

export default LangContext;
